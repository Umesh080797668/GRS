/**
 * Translates a standard API error message_key based on active dashboard language.
 */
export function translateMessageKey(key: string, lang?: Language): string | null {
  const currentLang =
    lang ||
    (typeof window !== 'undefined'
      ? (localStorage.getItem('grs_dashboard_lang') as Language) || 'en'
      : 'en');
  const table = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return table[key] || TRANSLATIONS.en[key] || null;
}
